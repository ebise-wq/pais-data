"""Extra GBD 2023 causes for the burden vs research comparison.

Each entry: label -> dict with
  group : "NCD" (non-cancer non-communicable), "Cancer", "Infectious", "NTD" (neglected tropical
          disease), "Maternal/neonatal"
  gbd   : list of GBD 2023 cause names (level 3 or 4) whose DALYs are summed
  pm    : PubMed title query
  cond  : ClinicalTrials.gov query.cond
  inc   : regex; a study is kept if one of its listed conditions matches
  exc   : optional regex; a study is dropped if every matching condition also matches this
          (and the title does not match inc)

Rules used to pick causes: a named disease (not an "other ..." residual group, not an injury,
not a risk factor) that a title search can find. Parent and child causes are never both used.
The 13 original comparators are not repeated here; they come from ../pubmed and ../clinicaltrials.
"""


def ti(*p):
    return "(" + " OR ".join(f'"{x}"[ti]' for x in p) + ")"


def raw(*p):
    return "(" + " OR ".join(f"{x}[ti]" for x in p) + ")"


def E(group, gbd, pm, cond, inc, exc=None):
    return dict(group=group, gbd=gbd if isinstance(gbd, list) else [gbd], pm=pm, cond=cond, inc=inc, exc=exc)


